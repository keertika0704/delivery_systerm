_SEV_LABEL = {"alert": "Needs attention", "watch": "Worth a look", "info": "For context"}

#: Insight kinds whose claim is about late rates; they need enough late *events*, not just enough orders.
_LATE_RATE_KINDS = frozenset({"region_high", "region_low", "region_test", "month_high", "month_extremes",
                              "category_delay", "same_state", "processing_time"})
MIN_LATE_EVENTS = 20


def _enough_late_events(items: list, n_late: int) -> list:
    """Drop late-rate findings when the view holds fewer than MIN_LATE_EVENTS late orders (a rate gap resting on a
    handful of events is noise, however many orders there are)."""
    if n_late >= MIN_LATE_EVENTS:
        return list(items)
    return [i for i in items if getattr(i, "kind", None) not in _LATE_RATE_KINDS]


# --------------------------------------------------------------------------- #
# Cached computations (keyed on the filter values, not on the 96k-row frame)
# --------------------------------------------------------------------------- #
def _data_key(flt: dict) -> tuple:
    try:
        mtime = config.ORDERS_DELIVERED_PATH.stat().st_mtime_ns
    except OSError:
        mtime = -1
    s, e = flt["date_range"]
    return (str(s), str(e), tuple(flt["states"]), tuple(flt["categories"]), flt["n_total"], flt["n_filtered"], mtime)


@st.cache_data(show_spinner=False)
def _overview_tables(_df, key: tuple, min_orders: int) -> dict:
    return {
        "kpi": analytics.kpi_summary(_df),
        "duration": analytics.duration_summary(_df),
        "monthly": analytics.monthly_performance(_df, min_orders=min_orders),
    }


@st.cache_data(show_spinner=False)
def _all_kpis(_df_all, key: tuple) -> dict:
    return analytics.kpi_summary(_df_all)


@st.cache_data(show_spinner=False)
def _state_table(_df, key: tuple, min_orders: int):
    return analytics.state_performance(_df, min_orders=min_orders)


@st.cache_data(show_spinner="Computing headline findings…")
def _insights(_df, key: tuple, min_orders: int):
    # same filter as the Reports page: a single state / category in view is not compared with itself
    return exports.comparable_insights(insights_mod.generate_insights(_df, min_orders=min_orders), min_orders)


