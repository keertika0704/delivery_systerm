def _note(text: ot.Interpretation, kind: str = "Observed finding", compact: bool = False) -> None:
    """'What this shows' card: an observed block and, if present, a suggested next step."""
    cls = "stat" if kind.startswith("Statistical") else "obs"
    rows = f'<div class="diq-note-row"><span class="diq-chip {cls}">{ui.esc(kind)}</span>' \
           f'<p class="diq-note-text">{ui._inline_md(text.observed)}</p></div>'
    if text.action:
        rows += ('<div class="diq-note-row"><span class="diq-chip act">Suggested next step</span>'
                 f'<p class="diq-note-text">{ui._inline_md(text.action)}</p></div>')
    st.html(f'<div class="diq-note{" compact" if compact else ""}">{rows}</div>')


def _delta(value: float | None, ref: float | None, *, kind: str, lower_is_better: bool, active: bool) -> dict:
    """KPI delta versus the unfiltered data (only when filters are active)."""
    if not active or value is None or ref is None:
        return {}
    try:
        diff = float(value) - float(ref)
    except (TypeError, ValueError):
        return {}
    if diff != diff:  # NaN
        return {}
    if kind == "pp":
        text, tiny = f"{ui.fmt_pp(diff)} vs all orders", abs(diff) < 0.0005
    else:
        text, tiny = f"{diff:+.1f} days vs all orders", abs(diff) < 0.05
    tone = "neutral" if tiny else (("good" if diff < 0 else "bad") if lower_is_better else ("good" if diff > 0 else "bad"))
    return {"delta": text, "delta_tone": tone}


def _kpis(k: dict, k_all: dict, flt: dict) -> None:
    n, n_total = k["n_orders"], flt["n_total"]
    act = bool(flt["active"])
    lo, hi = analytics.wilson_ci(k["n_late"], n)
    share = f"{100 * n / n_total:.1f}% of all delivered orders" if n_total else ""
    ui.kpi_row([
        dict(label="Delivered orders", value=ui.fmt_int(n), icon="package", accent="blue",
             sublabel=f"{ui.fmt_int(n)} of {ui.fmt_int(n_total)} orders · {share}",
             help="Delivered orders that match the sidebar filters."),
        dict(label="On-time rate", value=ui.fmt_pct(k["on_time_rate"]), icon="check", accent="green",
             sublabel=f"{ui.fmt_int(n - k['n_late'])} on time or early ({ui.fmt_n(n)})",
             help="Share of orders delivered on or before the estimated delivery date.",
             **_delta(k["on_time_rate"], k_all.get("on_time_rate"), kind="pp", lower_is_better=False, active=act)),
        dict(label="Late-delivery rate", value=ui.fmt_pct(k["late_rate"]), icon="alert", accent="red",
             sublabel=f"{ui.fmt_int(k['n_late'])} late · 95% CI {ui.fmt_pct(lo)} to {ui.fmt_pct(hi)}",
             help="Share of orders delivered after the estimated delivery date (calendar-date basis).",
             **_delta(k["late_rate"], k_all.get("late_rate"), kind="pp", lower_is_better=True, active=act)),
        dict(label="Avg delivery time", value=ui.fmt_days(k["mean_duration"]), icon="truck", accent="blue",
             sublabel=f"Median {ui.fmt_days(k['median_duration'])} · purchase to customer",
             **_delta(k["mean_duration"], k_all.get("mean_duration"), kind="days", lower_is_better=True, active=act)),
    ])
    ui.kpi_row([
        dict(label="Avg lateness (late orders)", value=ui.fmt_days(k["mean_late_days"]), icon="clock", accent="amber",
             sublabel=(f"Among {ui.fmt_int(k['n_late'])} late orders" if k["n_late"] else "No late orders in this view"),
             help="Mean days after the estimated date, over late orders only."),
        dict(label="Median delivery time", value=ui.fmt_days(k["median_duration"]), icon="clock", accent="slate",
             sublabel="Half of the orders arrived faster than this"),
        dict(label="Total freight value", value=ui.fmt_money_brl(k["total_freight"], 0), icon="dollar", accent="slate",
             sublabel=f"Sum of freight over {ui.fmt_int(n)} orders"),
        dict(label="Customer states covered", value=ui.fmt_int(k["n_states"]), icon="map-pin", accent="slate",
             sublabel=f"of {len(config.STATE_NAMES)} Brazilian states"),
    ])


def _headline_strip(items: list, flt: dict) -> None:
    ui.section_header("Headline findings", "The most notable computed findings for the orders in view (alerts first). "
                      "Intervals and caveats are in the full text below.", icon="trend")
    cards = []
    for ins in items:
        sev = ins.severity if ins.severity in _SEV_LABEL else "info"
        foot = f"Based on {ins.n:,} orders" if ins.n else ""
        notice = getattr(ins, "kind", None) == "insufficient_data"   # a notice, not a finding: no lead, no intervals
        label = "Notice" if notice else ot.insight_label(ins)
        caveat = "" if notice else f'<div class="diq-find-caveat">{ui.esc(ot.insight_caveat(ins))}</div>'
        cards.append(f'<div class="diq-find {sev}"><div class="diq-find-top"><span class="diq-sev">{_SEV_LABEL[sev]}</span>'
                     f'<span class="diq-find-kind">{ui.esc(label)}</span></div>'
                     f'<div class="diq-find-title">{ui.esc(ins.title)}</div>'
                     f'<div class="diq-find-text">{ui.esc(ot.teaser(ins.text))}</div>'
                     f'{caveat}'
                     f'<div class="diq-find-foot">{ui.esc(foot)}</div></div>')
    st.html(f'<div class="diq-find-grid">{"".join(cards)}</div>')
    with st.expander("Read the full text of these findings", expanded=False):
        for ins in items:
            ui.insight_box(ins)
    _page_links()


def _page_link(path: str, label: str, icon: str, key: str) -> None:
    try:
        st.page_link(path, label=label, icon=icon)
    except Exception:  # page not registered (page run on its own, e.g. in tests)
        st.caption(f"{label} (open from the sidebar)")


def _page_links() -> None:
    c1, c2, c3 = st.columns(3)
    with c1:
        _page_link("views/2_Delay_Analysis.py", "Delay Analysis: what drives delays", ":material/query_stats:", "a")
    with c2:
        _page_link("views/3_Regional_Intelligence.py", "Regional Intelligence: states & routes", ":material/map:", "b")
    with c3:
        _page_link("views/5_Reports_Insights.py", "Reports & Insights: all findings", ":material/description:", "c")


def _model_pointer() -> None:
    """One honest line about where model predictions live (numbers come from the metrics file)."""
    metrics = ui.get_model_metrics() or {}
    try:
        sel = (metrics.get("selected_model") or {}).get("name")
        test = metrics["models"][sel]["test"]
        extra = (f" Its test-window ROC-AUC is {ui.fmt_num(test['roc_auc'], 2)} and PR-AUC {ui.fmt_num(test['pr_auc'], 2)}: "
                 "a modest signal that is far from precise, so treat scores as rough triage, not as predictions to rely on.")
    except (KeyError, TypeError):
        extra = ""
    st.caption("Model predictions are kept separate from the observed figures above: the Delay Prediction page scores "
               "individual orders from information available at purchase." + extra)


